# Définir le chemin vers la base SQLite
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
words_db_path = os.path.join(BASE_DIR, "words.db")

# Variable globale pour stocker le dictionnaire de mots
WORD_DICT = None


# Fonction : charger les mots depuis la base SQLite
def load_word_dictionary():
    global WORD_DICT
    if WORD_DICT is None:
        print("Chargement de words.db au démarrage...")
        try:
            conn = sqlite3.connect(words_db_path)
            cursor = conn.cursor()
            WORD_DICT = {}
            languages = ["fr", "en", "es", "de", "it"]
            for lang in languages:
                cursor.execute("SELECT word FROM words WHERE language = ?", (lang,))
                words = [row[0] for row in cursor.fetchall()]
                WORD_DICT[lang] = words
                print(f"Chargé {len(words)} mots pour {lang} depuis words.db")
            conn.close()
        except sqlite3.Error as e:
            print(f"Erreur lors du chargement de words.db : {e}")
            raise
    return WORD_DICT


# Charger au démarrage
load_word_dictionary()


# Fonction : obtenir l’article selon la langue et le genre
def get_article(lang, gender):
    if lang == "fr":
        return "le " if gender == "m" else "la "
    elif lang == "en":
        return "the "
    else:
        return ""
